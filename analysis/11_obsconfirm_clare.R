# =============================================================================
# 11_obsconfirm_clare.R
# Follow-up of 08 and 10 (item 4 of the revision): the observation-confirmation
# design with false positives that depend on the occupancy covariate itself
# (correlation 1.0, so w = x), the structure examined by Clare et al. (2021).
# Same design and ecology as 08 (300 sites, 20 occasions, psi = 0.5, p11 = 0.6,
# slope -0.8, no separately verified sites, a fraction of the automated
# occasions checked):
#   cells (18): conf_effect in {0.5, 1.0, 1.5} x p10 in {0.05, 0.20} x
#               frac_confirmed in {0.05, 0.10, 0.30}
#   models: fp ~ 1, fp ~ x (here the generating model), and a single-season
#           occupancy model that ignores false positives (unmarked::occu on the
#           automated detections; Wald 95% interval), the reference against
#           which Clare et al. measured the reduction in bias
# 100 replicates per cell, simulated and fitted with the crywolf package
# (installed version): 4 chains of 1000 + 1000 iterations, adapt_delta =
# 0.95, one core per fit. Seeds start at 11001, apart from those of 08 and 10.
#
# Each task is saved in data/obsconfirm_clare_jobs/ as soon as it ends and
# skipped on a rerun, so an interrupted run resumes where it stopped.
# Run from the compendium root, without the renv library:
#   RENV_ACTIVATE_PROJECT=FALSE WORKERS=16 Rscript analysis/11_obsconfirm_clare.R
# REPS (default 100) sets the number of replicates. Do not edit this file
# while it runs: Rscript reads it as it goes.
# =============================================================================
library(crywolf)

reps <- as.integer(Sys.getenv("REPS", "100"))
workers <- as.integer(Sys.getenv("WORKERS", "16"))
job_dir <- file.path("data", "obsconfirm_clare_jobs")
dir.create(job_dir, showWarnings = FALSE)

cells <- expand.grid(p10 = c(0.05, 0.20), frac_confirmed = c(0.05, 0.10, 0.30),
                     conf_effect = c(0.5, 1.0, 1.5), conf_cor = 1.0)
cells$cell <- seq_len(nrow(cells))
tasks <- expand.grid(rep = seq_len(reps), cell = cells$cell)
tasks$seed <- 11000 + seq_len(nrow(tasks))

# one model fitted to one dataset -> one row
fit_one <- function(d, truth, fp, model, seed) {
  t0 <- Sys.time()
  res <- tryCatch({
    m <- suppressWarnings(fp_occu(
      d, occ = ~ x, fp = fp, random_recorder = FALSE, chains = 4,
      parallel_chains = 1, threads_per_chain = 1, iter_warmup = 1000,
      iter_sampling = 1000, adapt_delta = 0.95, seed = seed, refresh = 0,
      show_messages = FALSE))
    s <- summary(m)$table
    list(ok = TRUE, b1 = s[s$variable == "occ_x", ], p10 = s[s$variable == "p10_bar", ],
         w = s[s$variable == "fp_w", ], diag = m$diagnostics)
  }, error = function(e) list(ok = FALSE, msg = conditionMessage(e)))
  na <- NA_real_
  ok <- isTRUE(res$ok)
  g <- function(part, col) if (ok && nrow(res[[part]]) == 1) res[[part]][[col]] else na
  data.frame(
    model = model, ok = ok, msg = if (ok) NA_character_ else res$msg,
    true_b1 = truth$b1, true_p10_bar = truth$p10_marginal,
    b1_est = g("b1", "mean"), b1_lo = g("b1", "lower"), b1_hi = g("b1", "upper"),
    p10_est = g("p10", "mean"), p10_lo = g("p10", "lower"), p10_hi = g("p10", "upper"),
    fp_w_est = g("w", "mean"), fp_w_lo = g("w", "lower"), fp_w_hi = g("w", "upper"),
    max_rhat = if (ok) res$diag$max_rhat else na,
    min_ess_bulk = if (ok) res$diag$min_ess_bulk else na,
    ndiv = if (ok) res$diag$divergences else na,
    seconds = as.numeric(difftime(Sys.time(), t0, units = "secs")))
}

# single-season occupancy ignoring false positives: unmarked::occu(~ 1 ~ x) on
# the automated detections, with a Wald 95% interval for the slope
fit_naive <- function(d, truth) {
  t0 <- Sys.time()
  na <- NA_real_
  res <- tryCatch({
    a <- d$auto
    y <- matrix(NA_integer_, max(a$site), max(a$occasion))
    y[cbind(a$site, a$occasion)] <- a$y
    umf <- unmarked::unmarkedFrameOccu(y = y, siteCovs = data.frame(x = d$sites$x[order(d$sites$site)]))
    m <- unmarked::occu(~ 1 ~ x, data = umf)
    est <- unmarked::coef(m)[["psi(x)"]]
    se <- sqrt(diag(unmarked::vcov(m)))[["psi(x)"]]
    list(ok = is.finite(est) && is.finite(se), b1 = est, se = se)
  }, error = function(e) list(ok = FALSE, msg = conditionMessage(e)))
  ok <- isTRUE(res$ok)
  data.frame(
    model = "naive", ok = ok, msg = if (ok) NA_character_ else if (is.null(res$msg)) "non-finite estimate" else res$msg,
    true_b1 = truth$b1, true_p10_bar = truth$p10_marginal,
    b1_est = if (ok) res$b1 else na,
    b1_lo = if (ok) res$b1 - 1.96 * res$se else na, b1_hi = if (ok) res$b1 + 1.96 * res$se else na,
    p10_est = na, p10_lo = na, p10_hi = na, fp_w_est = na, fp_w_lo = na, fp_w_hi = na,
    max_rhat = na, min_ess_bulk = na, ndiv = na,
    seconds = as.numeric(difftime(Sys.time(), t0, units = "secs")))
}

run_one <- function(rep, cell, seed) {
  f <- file.path(job_dir, sprintf("cell%02d-rep%03d.rds", cell, rep))
  if (file.exists(f)) return(readRDS(f))
  cfg <- cells[cell, ]
  sim <- simulate_fp(nsite = 300, nocc = 20, psi = 0.5, b1 = -0.8, p11 = 0.6,
                     p10 = cfg$p10, conf_effect = cfg$conf_effect,
                     conf_cor = cfg$conf_cor, frac_verified = 0,
                     frac_confirmed = cfg$frac_confirmed, seed = seed)
  models <- list(constant = ~ 1, fp_x = ~ x)
  rows <- purrr::imap(models, function(fp, name)
    fit_one(sim$data, sim$truth, fp, name, seed)) |> purrr::list_rbind()
  rows <- rbind(rows, fit_naive(sim$data, sim$truth))
  out <- cbind(rep = rep, cell = cell, seed = seed, cfg[c("p10", "frac_confirmed",
                                                         "conf_effect", "conf_cor")],
               n_checked = sum(!is.na(sim$data$auto$n_true)), rows)
  saveRDS(out, f)
  out
}

crywolf::fp_compile()   # once, before the workers
future::plan(future::multisession, workers = workers)
t0 <- Sys.time()
res <- furrr::future_pmap(tasks, run_one,
                          .options = furrr::furrr_options(seed = TRUE, chunk_size = 1)) |>
  purrr::list_rbind()
attr(res, "hours") <- as.numeric(difftime(Sys.time(), t0, units = "hours"))
saveRDS(res, file.path("data", "fp_obsconfirm_clare_results.rds"))
message("done: ", nrow(res), " fits in ", round(attr(res, "hours"), 1), " h")
