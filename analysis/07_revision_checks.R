# =============================================================================
# 07_revision_checks.R
# Checks added in the revision of the manuscript (see R/fp_revision.R):
#   homogeneous cells (9)       -> fp ~ 1 and fp ~ x   (cost of the fix; LOO false alarms)
#   unstructured cells (4)      -> fp ~ 1 and random_fp (does a site effect fix it?)
#   structured core cells (4)   -> fp ~ 1 and fp ~ x   (do LOO and the PPC flag it?)
# 100 replicates per cell, the first 100 datasets of 01_run_simulation.R,
# regenerated and checked against data/fp_sim_results.rds before fitting.
# Fits use the crywolf package (installed version), 4 chains of 1000 + 1000
# iterations, adapt_delta = 0.95, one core per fit.
#
# Each task is saved in data/revision_jobs/ as soon as it ends and skipped on
# a rerun, so an interrupted run resumes where it stopped.
# Run from the compendium root, without the renv library (crywolf is not in
# renv.lock):
#   RENV_ACTIVATE_PROJECT=FALSE WORKERS=16 Rscript analysis/07_revision_checks.R
# Do not edit this file while it runs: Rscript reads it as it goes.
# =============================================================================
library(crywolf)
source("R/fp_sim_pilot.R")
source("R/fp_revision.R")

reps <- as.integer(Sys.getenv("REPS", "100"))
workers <- as.integer(Sys.getenv("WORKERS", "16"))
job_dir <- file.path("data", "revision_jobs")
dir.create(job_dir, showWarnings = FALSE)

des <- revision_designs()
tasks <- dplyr::bind_rows(
  revision_tasks(des$main, 100, 1000, "main"),
  # the structured core cells are the first four of the confusion design;
  # the original run had 300 replicates there, of which the first 100
  # have the same seeds as a run of 100
  revision_tasks(des$conf, 300, 5000, "conf") |> dplyr::filter(cell <= 4))
tasks <- tasks[tasks$rep <= reps, ]

ok <- check_regeneration(tasks, des, readRDS(file.path("data", "fp_sim_results.rds")))
if (!all(ok)) stop(sum(!ok), " regenerated datasets differ from the original run.")
message(nrow(tasks), " datasets regenerated and matched.")

crywolf::fp_compile()   # once, before the workers
run_one <- function(rep, cell, seed, run) {
  f <- file.path(job_dir, sprintf("%s-cell%02d-rep%03d.rds", run, cell, rep))
  if (file.exists(f)) return(readRDS(f))
  out <- run_revision_task(des, rep, cell, seed, run)
  saveRDS(out, f)
  out
}
future::plan(future::multisession, workers = workers)
t0 <- Sys.time()
res <- furrr::future_pmap(tasks, run_one,
                          .options = furrr::furrr_options(seed = TRUE, chunk_size = 1)) |>
  purrr::list_rbind()
attr(res, "hours") <- as.numeric(difftime(Sys.time(), t0, units = "hours"))
saveRDS(res, file.path("data", "fp_revision_results.rds"))
message("done: ", nrow(res), " fits in ", round(attr(res, "hours"), 1), " h")
